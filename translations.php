    private static $currentLang = 'fa';

    public static function init()
    {
        if (session_status() === PHP_SESSION_NONE) {
            session_start();
        }

        // Check language switch from GET parameter
        if (isset($_GET['lang']) && array_key_exists($_GET['lang'], self::$languages)) {
            $_SESSION['admin_lang'] = $_GET['lang'];
            setcookie('admin_lang', $_GET['lang'], time() + (86400 * 365), '/');
            self::$currentLang = $_GET['lang'];
        } elseif (!empty($_SESSION['admin_lang']) && array_key_exists($_SESSION['admin_lang'], self::$languages)) {
            self::$currentLang = $_SESSION['admin_lang'];
        } elseif (!empty($_COOKIE['admin_lang']) && array_key_exists($_COOKIE['admin_lang'], self::$languages)) {
            self::$currentLang = $_COOKIE['admin_lang'];
        } else {
            self::$currentLang = 'fa';
        }
    }

    public static function getLang()
    {
        return self::$currentLang;
    }

    public static function getDir()
    {
        return self::$languages[self::$currentLang]['dir'] ?? 'rtl';
    }

    public static function t($key, $default = '')
    {
        $lang = self::$currentLang;
        return self::$strings[$lang][$key] ?? self::$strings['en'][$key] ?? ($default ?: $key);
    }


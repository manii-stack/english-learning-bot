<?php
/**
 * Telegram Webhook Handler
 * Receives incoming Telegram updates, processes English corrections with multi-key Gemini rotation,
 * and handles callback queries from inline buttons.
 *
 * @author Mohammadreza Sarmadi
 */

define('BOT_APP', true);

require_once __DIR__ . '/config.php';
require_once __DIR__ . '/settings.php';
require_once __DIR__ . '/gemini.php';
require_once __DIR__ . '/telegram.php';

// Send initial 200 OK response to Telegram
http_response_code(200);
header('Content-Type: application/json');

// Validate optional webhook secret token
$secretToken = SettingsManager::get('telegram_secret_token', defined('TELEGRAM_SECRET_TOKEN') ? TELEGRAM_SECRET_TOKEN : '');
if (!empty($secretToken)) {
    $receivedToken = $_SERVER['HTTP_X_TELEGRAM_BOT_API_SECRET_TOKEN'] ?? '';
    if ($receivedToken !== $secretToken) {
        bot_log("Webhook Secret Token Mismatch! Received: " . $receivedToken);
        exit(json_encode(['error' => 'Unauthorized']));
    }
}

// Read raw JSON update payload from Telegram
$rawInput = file_get_contents('php://input');
if (empty($rawInput)) {
    exit(json_encode(['status' => 'No input']));
}

$update = json_decode($rawInput, true);
if (!$update) {
    bot_log("Invalid JSON received: " . $rawInput);
    exit(json_encode(['error' => 'Invalid JSON']));
}

$bot = new TelegramBot();

// =============================================================
// 1. Handle Inline Button Click Event (Callback Query - Retry)
// =============================================================
if (isset($update['callback_query'])) {
    $cq = $update['callback_query'];
    $cqId = $cq['id'];
    $cqData = $cq['data'] ?? '';
    $botMsg = $cq['message'] ?? [];
    $chatId = $botMsg['chat']['id'] ?? null;
    $botMsgId = $botMsg['message_id'] ?? null;

    if ($cqData === 'retry_analysis') {
        // Immediate notification to clear the loading hourglass on the client
        $bot->answerCallbackQuery($cqId, "🔄 در حال بررسی مجدد و ارائه پیشنهادات جدید...");

        // Extract original user message that the bot replied to
        $originalText = $botMsg['reply_to_message']['text'] ?? '';

        if (!empty($originalText)) {
            $gemini = new GeminiService();
            // Re-evaluate with isRetry=true for fresh alternatives
            $newAnalysis = $gemini->analyzeSentence($originalText, true);

            if ($newAnalysis && !empty($newAnalysis['should_reply'])) {
                $newFormatted = TelegramBot::formatCorrectionMessage($newAnalysis);
                $retryKeyboard = SettingsManager::get('enable_retry_button', true) ? TelegramBot::getRetryKeyboard() : null;
                $bot->editMessageText($chatId, $botMsgId, $newFormatted, 'HTML', $retryKeyboard);
            }
        }
    } else {
        $bot->answerCallbackQuery($cqId);
    }
    exit(json_encode(['status' => 'callback_processed']));
}

// =============================================================
// 2. Handle Standard Text Messages (Message Update)
// =============================================================
if (isset($update['message'])) {
    $message = $update['message'];
    $chatId = $message['chat']['id'] ?? null;
    $chatType = $message['chat']['type'] ?? 'unknown';
    $messageId = $message['message_id'] ?? null;
    $fromUser = $message['from'] ?? [];
    $isBot = $fromUser['is_bot'] ?? false;
    $text = trim($message['text'] ?? '');

    // Ignore messages generated by bots
    if ($isBot) {
        exit(json_encode(['status' => 'Ignored bot message']));
    }

    // Direct /start command handler in private chats
    if ($chatType === 'private') {
        if ($text === '/start') {
            $welcome = "👋 <b>سلام! من ربات هوشمند اصلاح زبان انگلیسی هستم.</b>\n\n";
            $welcome .= "🔹 من با مدل‌های پیشرفته <b>Google Gemini</b> کار می‌کنم تا خطاهای گرامری، املایی و لحن جملات را سریع تصحیح کنم.\n\n";
            $welcome .= "👥 <b>نحوه استفاده در گروه:</b>\n";
            $welcome .= "1. من را به گروه چت انگلیسی خود اضافه کنید.\n";
            $welcome .= "2. حتماً در @BotFather تنظیمات <b>Privacy Mode</b> من را <b>Disable</b> کنید.\n";
            $welcome .= "3. به انگلیسی چت کنید؛ اگر جمله‌ای اشکال داشته باشد، فوراً آن را تصحیح کرده و راه‌های طبیعی‌تر گفتن آن را پیشنهاد می‌دهم!\n\n";
            $welcome .= "✨ همچنین می‌توانید همین‌جا یک جمله انگلیسی بفرستید تا برایتان تست کنم!";
            $bot->sendMessage($chatId, $welcome);
            exit(json_encode(['status' => 'Start sent']));
        }
    }

    // Ignore commands starting with slash
    if (strpos($text, '/') === 0) {
        exit(json_encode(['status' => 'Ignored command']));
    }

    // Validate minimum text length
    $minLength = SettingsManager::get('min_text_length', 5);
    if (empty($text) || mb_strlen($text) < $minLength) {
        exit(json_encode(['status' => 'Ignored short text']));
    }

    // Analyze message with Gemini (intelligent key rotation & fallback models)
    $gemini = new GeminiService();
    $analysis = $gemini->analyzeSentence($text, false);

    if (!$analysis) {
        exit(json_encode(['status' => 'No analysis generated']));
    }

    // Reply if errors or typos are found
    if (!empty($analysis['should_reply']) && !empty($analysis['has_errors'])) {
        $formattedReply = TelegramBot::formatCorrectionMessage($analysis);
        if (!empty($formattedReply)) {
            $enableRetry = SettingsManager::get('enable_retry_button', true);
            $keyboard = $enableRetry ? TelegramBot::getRetryKeyboard() : null;
            $bot->sendMessage($chatId, $formattedReply, $messageId, 'HTML', $keyboard);
        }
    }
    // Add thumbs-up reaction if message is completely natural and correct
    elseif (!empty($analysis['is_perfect']) && SettingsManager::get('react_if_perfect', true)) {
        $bot->setMessageReaction($chatId, $messageId, '👍');
    }
}

echo json_encode(['status' => 'ok']);
